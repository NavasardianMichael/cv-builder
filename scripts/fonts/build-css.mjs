#!/usr/bin/env node
/**
 * public/fonts/manifest.json -> public/fonts/cv-fonts.css.
 *
 * One `@font-face` per weight/style a font ships. The family name is `cv-<slug>` — the same
 * string `cvFontFamily()` in src/constants/fonts.ts produces — so a CV's design stores a slug
 * and never a raw font-family string. Browsers download a face only when text uses it, so
 * declaring all twenty costs nothing until the editor's font picker or a CV asks for one.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const fontsDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../public/fonts')
const manifest = JSON.parse(readFileSync(path.join(fontsDir, 'manifest.json'), 'utf8'))

const faces = Object.entries(manifest).flatMap(([slug, entries]) =>
  entries.map(
    (face) =>
      `@font-face {\n  font-family: 'cv-${slug}';\n  src: url('/fonts/${face.file}') format('woff2');\n` +
      `  font-weight: ${face.weight};\n  font-style: ${face.style};\n  font-display: swap;\n}\n`
  )
)

writeFileSync(
  path.join(fontsDir, 'cv-fonts.css'),
  `/* Generated by scripts/fonts/build-css.mjs from manifest.json — do not edit. */\n\n${faces.join('\n')}`
)
console.log(`[fonts] ${faces.length} faces -> public/fonts/cv-fonts.css`)
